#!/usr/bin/env python3
"""Fill the answer cache with prepared questions and pin the entries.

Run on the server, from the checkout of the running app, so `.env` and
ANSWER_CACHE_PATH resolve as for the app. Answers are generated by the running
app over HTTP, exactly as for a visitor, so the entries have the keys visitors
hit; the script then pins them in the cache file, which keeps them past the TTL
and the size cap. Pinning is never possible over HTTP.

    uv run python scripts/warm_cache.py --dry-run
    uv run python scripts/warm_cache.py --wp WP1-historie --profile all
    uv run python scripts/warm_cache.py --questions my_questions.txt --model gpt-4.1-mini --model gpt-4.1
    uv run python scripts/warm_cache.py --force   # regenerate the pinned answers

Requests are built the way the browser builds them with its default settings:
the WP's default collection, the model's context window, and the profile's
prompts. A visitor who changed a setting (or uses a profile saved only in their
browser) asks a different request and is not served the warmed answer.

Defaults for the options can be kept in data/warm_cache.json (see
scripts/warm_cache.example.json); options on the command line win.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter
from collections.abc import Callable, Generator, Iterable, Iterator
from contextlib import closing
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.answer_cache import AnswerCache  # noqa: E402
from app.config import get_settings  # noqa: E402

DEFAULT_CONFIG = ROOT / "data" / "warm_cache.json"
DEFAULTS: dict[str, Any] = {
    "url": "http://127.0.0.1:8000",
    "wp": ["all"],
    "questions": "prepared",
    "profile": ["default"],
    "provider": None,
    "model": [],
}

Fetch = Callable[[str, dict[str, str]], Any]


@dataclass
class Job:
    wp_id: str
    profile_id: str
    model: str
    question: str
    body: dict[str, Any]

    def label(self) -> str:
        return f"{self.wp_id} · {self.profile_id} · {self.model or 'výchozí model'} · {self.question}"


def builtin_profiles(wp: dict[str, Any]) -> list[dict[str, Any]]:
    return [{**preset, "wp_id": wp["id"]} for preset in wp.get("builtin_prompts") or []]


def default_profile_id(wp: dict[str, Any]) -> str:
    builtins = builtin_profiles(wp)
    return wp.get("default_prompt_id") or (builtins[0]["id"] if builtins else "")


def select_profiles(wp: dict[str, Any], shared: list[dict[str, Any]], wanted: Iterable[str]) -> list[dict[str, Any]]:
    """The WP's profiles named by ``wanted``: default, builtin, shared, all or ids."""

    builtins = builtin_profiles(wp)
    shared = [preset for preset in shared if preset.get("wp_id") == wp["id"]]
    by_id = {preset["id"]: preset for preset in builtins + shared}
    selected: dict[str, dict[str, Any]] = {}
    for name in wanted:
        if name == "default":
            ids = [default_profile_id(wp)]
        elif name == "builtin":
            ids = [preset["id"] for preset in builtins]
        elif name == "shared":
            ids = [preset["id"] for preset in shared]
        elif name == "all":
            ids = list(by_id)
        else:
            ids = [name]
        for profile_id in ids:
            if profile_id in by_id:
                selected.setdefault(profile_id, by_id[profile_id])
    return list(selected.values())


def provider_config(app_settings: dict[str, Any], provider_id: str | None) -> dict[str, Any]:
    providers = app_settings.get("llm_providers") or []
    wanted = provider_id or app_settings.get("llm_provider")
    for provider in providers:
        if provider.get("id") == wanted:
            return provider
    raise SystemExit(f"Neznámý poskytovatel {wanted!r}; dostupní: {', '.join(p.get('id', '') for p in providers)}")


def wp_default_collection(wp: dict[str, Any]) -> str:
    """As wpDefaultCollectionMsearchId in app.js."""

    collections = wp.get("collections") or []
    preferred = next((c for c in collections if c.get("id") == wp.get("default_collection_id")), None)
    chosen = preferred or (collections[0] if collections else None)
    return (chosen or {}).get("msearch_collection_id") or ""


def model_context_window(app_settings: dict[str, Any], provider: dict[str, Any], model: str) -> int:
    """As selectedModelContextWindow in app.js, falling back to the server default."""

    windows = {**(app_settings.get("model_context_windows") or {}), **(provider.get("model_context_windows") or {})}
    for value in (windows.get(model), provider.get("default_context_window_tokens")):
        if isinstance(value, (int, float)) and value >= 1024:
            return int(value)
    return int(app_settings["token_budget_defaults"]["context_window_tokens"])


def request_body(
    app_settings: dict[str, Any],
    wp: dict[str, Any],
    profile: dict[str, Any],
    provider: dict[str, Any],
    model: str,
    question: str,
    admin_password: str | None,
) -> dict[str, Any]:
    """The first-turn body the browser sends with its default settings.

    Fields the browser fills from server defaults are left out: the server
    resolves them to the same values for the cache key.
    """

    model = model or provider.get("default_model") or ""
    retrieval = app_settings["retrieval_defaults"]
    msearch = app_settings["msearch_defaults"]
    return {
        "question": question,
        "wp_id": wp["id"],
        "prompt_preset_id": profile["id"],
        "placeholder_defs": profile.get("placeholders") or {},
        "system_prompt": profile.get("system_prompt") or None,
        "user_prompt_template": profile.get("user_prompt_template") or None,
        "conversation_history": [],
        "context_window_tokens": model_context_window(app_settings, provider, model),
        "model": model,
        "llm_provider": provider["id"],
        # Models that are not public need the shared password, as in the browser.
        "admin_password": admin_password or None,
        "top_k": msearch.get("max_results") if msearch.get("max_results") is not None else app_settings.get("top_k"),
        "retrieval_backend": "msearch",
        "msearch_collection": wp_default_collection(wp),
        "msearch_mode": "hybrid",
        "msearch_rescore": bool(retrieval.get("msearch_rescore")),
        "rerank_enabled": False,
    }


def read_questions(fetch: Fetch, wp_id: str, source: str) -> list[str]:
    if source == "prepared":
        return list(fetch("/questions", {"wp_id": wp_id})["questions"])
    lines = Path(source).read_text(encoding="utf-8").splitlines()
    return [line.strip() for line in lines if line.strip()]


def build_jobs(fetch: Fetch, options: dict[str, Any], admin_password: str | None) -> list[Job]:
    app_settings = fetch("/settings", {})
    shared = fetch("/prompt-presets", {})
    wps = app_settings["wps"]
    wanted_wps = options["wp"]
    if "all" not in wanted_wps:
        known = {wp["id"] for wp in wps}
        unknown = [wp_id for wp_id in wanted_wps if wp_id not in known]
        if unknown:
            raise SystemExit(f"Neznámé WP: {', '.join(unknown)}; dostupné: {', '.join(sorted(known))}")
        wps = [wp for wp in wps if wp["id"] in wanted_wps]
    provider = provider_config(app_settings, options["provider"])
    models = options["model"] or [provider.get("default_model") or ""]
    jobs: list[Job] = []
    for wp in wps:
        profiles = select_profiles(wp, shared, options["profile"])
        if not profiles:
            print(f"{wp['id']}: žádný vybraný profil", file=sys.stderr)
            continue
        questions = read_questions(fetch, wp["id"], options["questions"])
        for profile in profiles:
            for model in models:
                for question in questions:
                    body = request_body(app_settings, wp, profile, provider, model, question, admin_password)
                    jobs.append(Job(wp["id"], profile["id"], body["model"], question, body))
    return jobs


def sse_events(lines: Iterable[str]) -> Iterator[tuple[str, dict[str, Any]]]:
    name, data = "", []
    for line in lines:
        if line.startswith("event: "):
            name = line.removeprefix("event: ")
        elif line.startswith("data: "):
            data.append(line.removeprefix("data: "))
        elif not line and name:
            yield name, json.loads("\n".join(data) or "{}")
            name, data = "", []
    if name:
        yield name, json.loads("\n".join(data) or "{}")


def warm(stream: Callable[[dict[str, Any]], Generator[str, None, None]], cache: AnswerCache, job: Job, force: bool) -> str:
    """Generate (or find) one answer and pin it; returns the status to print."""

    body = {**job.body, "bypass_cache": True} if force else job.body
    with closing(stream(body)) as lines:
        for name, data in sse_events(lines):
            if name == "error":
                return f"chyba: {data.get('detail')}"
            if name == "sources" and data.get("cache_hit"):
                # Already cached: disconnect rather than sit through the replay.
                return "v mezipaměti" if _pin(cache, data.get("cache_key")) else _not_pinned()
            if name == "done":
                if not str(data.get("answer") or "").strip():
                    return "chyba: prázdná odpověď"
                return "vygenerováno" if _pin(cache, data.get("cache_key")) else _not_pinned()
    return "chyba: odpověď skončila předčasně"


def _pin(cache: AnswerCache, key: str | None) -> bool:
    return bool(key) and cache.pin(key)


def _not_pinned() -> str:
    return "chyba: záznam v mezipaměti nenalezen (je mezipaměť zapnutá a ANSWER_CACHE_PATH stejná jako v aplikaci?)"


def load_options(args: argparse.Namespace) -> dict[str, Any]:
    config: dict[str, Any] = {}
    config_path = Path(args.config) if args.config else DEFAULT_CONFIG
    if args.config or config_path.exists():
        config = json.loads(config_path.read_text(encoding="utf-8"))
        unknown = set(config) - set(DEFAULTS)
        if unknown:
            raise SystemExit(f"{config_path}: neznámé volby {', '.join(sorted(unknown))}")
    options = {**DEFAULTS, **config}
    for name in DEFAULTS:
        value = getattr(args, name)
        if value is not None:
            options[name] = value
    return options


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate and pin cached answers for prepared questions.")
    parser.add_argument("--config", help=f"JSON with default options (default: {DEFAULT_CONFIG.relative_to(ROOT)} if it exists).")
    parser.add_argument("--url", help=f"The running app (default: {DEFAULTS['url']}).")
    parser.add_argument("--wp", action="append", help="WP id, repeatable, or 'all' (default).")
    parser.add_argument("--questions", help="'prepared' (the WP's prepared questions, default) or a file with one question per line.")
    parser.add_argument("--profile", action="append", help="'default' (the WP's default profile), 'builtin', 'shared', 'all' or a profile id; repeatable.")
    parser.add_argument("--provider", help="LLM provider id (default: the app's default provider).")
    parser.add_argument("--model", action="append", help="Model, repeatable (default: the provider's default model).")
    parser.add_argument("--force", action="store_true", help="Generate again even when cached, replacing the answer.")
    parser.add_argument("--dry-run", action="store_true", help="Only list the requests.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    options = load_options(args)
    settings = get_settings()
    if not settings.answer_cache_enabled:
        raise SystemExit("Mezipaměť odpovědí je vypnutá (ANSWER_CACHE_ENABLED).")
    if settings.auth_enabled:
        # Every request would need a logged-in session.
        raise SystemExit("S účty (AUTH_ENABLED) skript zatím nefunguje.")

    with httpx.Client(base_url=options["url"].rstrip("/"), timeout=httpx.Timeout(30.0, read=600.0)) as client:

        def fetch(path: str, params: dict[str, str]) -> Any:
            response = client.get(path, params=params)
            response.raise_for_status()
            return response.json()

        try:
            jobs = build_jobs(fetch, options, settings.admin_password)
        except httpx.HTTPError as exc:
            raise SystemExit(f"Aplikace na {options['url']} neodpovídá: {exc}") from exc
        if args.dry_run:
            for job in jobs:
                print(job.label())
            print(f"{len(jobs)} požadavků")
            return 0

        cache = AnswerCache(
            settings.answer_cache_path,
            ttl_seconds=settings.answer_cache_ttl_days * 86400,
            max_entries=settings.answer_cache_max_entries,
        )

        def stream(body: dict[str, Any]) -> Generator[str, None, None]:
            with client.stream("POST", "/chat/stream", json=body) as response:
                if response.status_code != 200:
                    response.read()
                    raise httpx.HTTPStatusError(response.text, request=response.request, response=response)
                yield from response.iter_lines()

        counts: Counter[str] = Counter()
        for index, job in enumerate(jobs, start=1):
            started = time.perf_counter()
            try:
                status = warm(stream, cache, job, args.force)
            except httpx.HTTPError as exc:
                status = f"chyba: {exc}"
            counts[status.split(":")[0]] += 1
            print(f"[{index}/{len(jobs)}] {status} ({time.perf_counter() - started:.1f} s) {job.label()}", flush=True)
    print(", ".join(f"{name}: {count}" for name, count in counts.items()) or "žádné požadavky")
    return 1 if counts["chyba"] else 0


if __name__ == "__main__":
    sys.exit(main())
